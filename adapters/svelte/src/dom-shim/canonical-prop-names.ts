// Why the shim needs a list of names at all. Svelte's compiler destroys two things a bare tag
// carries, and both are settled before any code of ours runs:
//
//   `<view testID="x">`        `fix_attribute_casing` lowercases every STATIC attribute name
//                              (transform-template/fix-attribute-casing.js) — `testid` reaches
//                              Fabric, which declares no such prop, and it is dropped on device.
//   `<pressable testID={v}>`   the same, for a DYNAMIC name, on any tag that is not an SVG
//                              element name (`get_attribute_name` -> `normalize_attribute`).
//   `<text-input multiline={false}>`
//                              a hyphenated tag takes `set_custom_element_data`, which stringifies
//                              a scalar and drops an object unless `get_setters(node)` finds a real
//                              prototype setter for that exact name (attributes.js:245-265).
//
// One list answers all three: an accessor per name defeats the stringifier, and the same names
// keyed by their lowercased spelling recover the casing in `setAttribute`. See `element.ts`.
//
// GENERATED from this adapter's own barrel — every `I*Props` type it exports, unioned through the
// TypeScript checker. That is the authoritative per-tag prop surface (`IViewProps` and its
// siblings), and it grows on its own when a primitive gains a prop or the barrel gains a type.
// `canonical-prop-names.test.ts` re-derives it and fails on any drift; regenerate with the snippet
// in that file's header rather than editing this array by hand.
//
// Deriving it from `react-native`'s own ViewConfig `validAttributes` was measured and rejected:
// it covers the NATIVE surface only, missing 110 of the 255 camelCase names our shared layer
